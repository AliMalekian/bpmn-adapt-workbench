"""Narrow authority-separated repository protocols."""
from __future__ import annotations

from typing import Any, Protocol


class CoreRepository(Protocol):
    def upsert_process(self, process_id, folder, name, narrative, bpmn_xml, rules, resources, states) -> None: ...
    def get_process(self, process_id) -> dict[str, Any] | None: ...
    def get_rules(self, process_id) -> list[dict[str, Any]]: ...
    def get_resources(self, process_id) -> list[dict[str, Any]]: ...
    def get_states(self, process_id) -> list[dict[str, Any]]: ...
    def create_run(self, run_id, process_id, fingerprint, status="running") -> None: ...
    def get_run(self, run_id) -> dict[str, Any] | None: ...


class RagRepository(Protocol):
    def add_approved_case(self, evidence_id, run_id, process_id, source_version_id,
                          operation, text, decision, metadata_json) -> None: ...
    def list_cases(self, process_id, active_only=False, operation=None,
                   source_version_id=None) -> list[dict[str, Any]]: ...
    def revoke_case(self, evidence_id, reason) -> None: ...
